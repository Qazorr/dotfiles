-- Launch rules match the spawned pid, and Hyprland spawns through `sh -c`:
-- `exec` makes the app that pid.
local function float_all()
	for _, window in ipairs(hl.get_workspace_windows(hl.get_active_workspace())) do
		hl.dispatch(hl.dsp.window.float({ action = "toggle", window = window }))
	end
end

local function cycle_to_top()
	hl.dispatch(hl.dsp.window.cycle_next())
	hl.dispatch(hl.dsp.window.bring_to_top())
end

